"""Migracje Alembic na SQLite: tworzą tabele zgodne z modelami (na PostgreSQL sprawdza to CI)."""

from pathlib import Path

import pytest
from alembic import command
from alembic.config import Config
from alembic.util.exc import AutogenerateDiffsDetected
from sqlalchemy import create_engine, inspect

ROOT = Path(__file__).resolve().parents[2]


@pytest.fixture
def alembic_cfg(tmp_path, monkeypatch):
    monkeypatch.setenv("AUDYTOR_DB_URL", f"sqlite:///{tmp_path / 'migracje.db'}")
    cfg = Config(str(ROOT / "alembic.ini"))
    cfg.set_main_option("script_location", str(ROOT / "migrations"))
    return cfg


def test_upgrade_creates_tables(alembic_cfg, tmp_path):
    command.upgrade(alembic_cfg, "head")
    tabele = set(inspect(create_engine(f"sqlite:///{tmp_path / 'migracje.db'}")).get_table_names())
    assert {"skan", "podstrona", "problem", "alembic_version"} <= tabele


def test_migrations_match_models(alembic_cfg):
    command.upgrade(alembic_cfg, "head")
    try:
        command.check(alembic_cfg)
    except AutogenerateDiffsDetected as exc:
        pytest.fail(f"Modele (src/audytor/db/models.py) różnią się od migracji – dodaj nową migrację:\n{exc}")


def test_downgrade_removes_tables(alembic_cfg, tmp_path):
    command.upgrade(alembic_cfg, "head")
    command.downgrade(alembic_cfg, "base")
    tabele = set(inspect(create_engine(f"sqlite:///{tmp_path / 'migracje.db'}")).get_table_names())
    assert tabele == {"alembic_version"}
